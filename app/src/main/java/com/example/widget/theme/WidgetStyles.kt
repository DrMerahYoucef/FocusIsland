package com.example.widget.theme

import androidx.annotation.ColorRes
import androidx.annotation.LayoutRes
import com.example.R
import com.example.ui.theme.AppStyle

/** Colour resources of one style's widgets (light/dark picked by the launcher from values-night). */
data class WidgetColorIds(
    @ColorRes val surfaceBase: Int,
    @ColorRes val hueVeilBase: Int,
    @ColorRes val rimBase: Int,
    @ColorRes val onSurface: Int,
    @ColorRes val onSurfaceVariant: Int,
    @ColorRes val accent: Int,
    @ColorRes val accentSoft: Int,
    @ColorRes val secondary: Int,
    @ColorRes val critical: Int,
    @ColorRes val track: Int
)

/**
 * Widgets follow the app style. Each style has its own copy of the layouts, generated by
 * scripts/gen_widget_styles.py (RemoteViews can't take a theme).
 */
object WidgetStyles {

    @LayoutRes
    fun countdownLayout(style: AppStyle) = when (style) {
        AppStyle.LAGOON -> R.layout.widget_countdown_layout
        AppStyle.ARCADE -> R.layout.widget_countdown_layout_arcade
        AppStyle.BLOSSOM -> R.layout.widget_countdown_layout_blossom
        AppStyle.EXPLORER -> R.layout.widget_countdown_layout_explorer
    }

    @LayoutRes
    fun matrixLayout(style: AppStyle) = when (style) {
        AppStyle.LAGOON -> R.layout.widget_exam_matrix_layout
        AppStyle.ARCADE -> R.layout.widget_exam_matrix_layout_arcade
        AppStyle.BLOSSOM -> R.layout.widget_exam_matrix_layout_blossom
        AppStyle.EXPLORER -> R.layout.widget_exam_matrix_layout_explorer
    }

    fun colors(style: AppStyle) = when (style) {
        AppStyle.LAGOON -> WidgetColorIds(
            R.color.wgt_surface_base, R.color.wgt_hue_veil_base, R.color.wgt_rim_base, R.color.wgt_on_surface,
            R.color.wgt_on_surface_variant, R.color.wgt_accent, R.color.wgt_accent_soft, R.color.wgt_secondary,
            R.color.wgt_critical, R.color.wgt_track
        )
        AppStyle.ARCADE -> WidgetColorIds(
            R.color.wgt_arcade_surface_base, R.color.wgt_arcade_hue_veil_base, R.color.wgt_arcade_rim_base, R.color.wgt_arcade_on_surface,
            R.color.wgt_arcade_on_surface_variant, R.color.wgt_arcade_accent, R.color.wgt_arcade_accent_soft, R.color.wgt_arcade_secondary,
            R.color.wgt_arcade_critical, R.color.wgt_arcade_track
        )
        AppStyle.BLOSSOM -> WidgetColorIds(
            R.color.wgt_blossom_surface_base, R.color.wgt_blossom_hue_veil_base, R.color.wgt_blossom_rim_base, R.color.wgt_blossom_on_surface,
            R.color.wgt_blossom_on_surface_variant, R.color.wgt_blossom_accent, R.color.wgt_blossom_accent_soft, R.color.wgt_blossom_secondary,
            R.color.wgt_blossom_critical, R.color.wgt_blossom_track
        )
        AppStyle.EXPLORER -> WidgetColorIds(
            R.color.wgt_explorer_surface_base, R.color.wgt_explorer_hue_veil_base, R.color.wgt_explorer_rim_base, R.color.wgt_explorer_on_surface,
            R.color.wgt_explorer_on_surface_variant, R.color.wgt_explorer_accent, R.color.wgt_explorer_accent_soft, R.color.wgt_explorer_secondary,
            R.color.wgt_explorer_critical, R.color.wgt_explorer_track
        )
    }
}
